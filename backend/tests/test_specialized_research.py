from backend.src.chains.research_chain import build_research_chain

def test_specialized_research_delegation():
    """Verify that Planner tags subtasks with categories and Researcher applies specialized prompts."""
    chain = build_research_chain()
    
    initial_state = {
        "original_query": "Compare MacBook Air M3 vs Dell XPS 13 on battery life benchmarks and starting price",
        "plan": None,
        "subtasks": [],
        "research_results": [],
        "analysis": "",
        "evaluation": None,
        "iteration_count": 0,
        "final_answer": ""
    }
    
    print("\n--- Running Specialized Multi-Domain Research Workflow ---")
    result = chain.invoke(initial_state)
    
    print("\n--- Categorized Subtasks Generated by Planner ---")
    categories_found = set()
    for t in result["subtasks"]:
        safe_title = t.title.encode("ascii", "replace").decode("ascii")
        category = getattr(t, "category", "general")
        print(f"  [{t.id}] ({category.upper()}) {safe_title}")
        categories_found.add(category)
        
    print(f"\nCategories detected: {categories_found}")
    print(f"Total Results Gathered: {len(result['research_results'])}")
    
    print("\n--- Final Answer with Specialized Extraction ---")
    safe_answer = result["final_answer"].encode("ascii", "replace").decode("ascii")
    print(safe_answer[:500] + "...\n")
    print("-------------------------------------------------")
    
    assert len(categories_found) >= 2, "Planner should categorize subtasks into multiple domains"
    assert len(result["research_results"]) >= 2
    print("SUCCESS: Specialized Research Delegation Verified!")

if __name__ == "__main__":
    test_specialized_research_delegation()
