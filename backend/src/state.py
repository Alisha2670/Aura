from typing import TypedDict, List, Dict, Any, Optional
from backend.src.schemas import SubTask, PlanOutput, EvaluationOutput

class ResearchState(TypedDict):
    """
    Centralized Graph State representing the shared memory of AURA.
    Every node in the LangGraph workflow reads from and writes to this dictionary.
    """
    original_query: str                          # The initial question from the user
    plan: Optional[PlanOutput]                   # The structured plan generated by Planner
    subtasks: List[SubTask]                      # List of decomposed research subtasks
    research_results: List[Dict[str, Any]]       # Gathered research findings and URLs
    analysis: str                                # Synthesized analysis produced by Analyst
    evaluation: Optional[EvaluationOutput]       # Quality critique from Evaluator
    iteration_count: int                         # Number of research retry loops executed
    final_answer: str                            # The formatted response for the user
